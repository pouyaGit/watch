"""JWT/authentication hypothesis schema (Stage R47.3).

A :class:`JWTAuthenticationHypothesisPlan` is a deterministic research
hypothesis about possible authentication/JWT validation or control behavior.
It answers the research question:

    "Which authentication/JWT research hypothesis follows from the supplied
     context?"

Hard boundaries encoded here:

- Research hypothesis only: no exploit claim, no vulnerability confirmation,
  no signature bypass, no authentication bypass, no token forgery, no
  credential testing, no payload, no attack sequence, no execution.
- Technology presence is never a hypothesis of weakness by itself.
- Closed vocabularies: hypothesis type, hypothesis state, supporting signals,
  confidence, priority, rationale and limitations are closed/bounded.
- Confidence and priority reuse the shared evidence-confidence vocabulary.
  Priority means "how useful is further research of this authentication
  hypothesis?"; it is NOT severity, exploitability, CVSS or vulnerability
  probability.
- ``hypothesis_state`` explicitly distinguishes an observed control, an
  observed weakness, a not-observed signal and a need for evidence.
- Bounded, privacy-safe, JSON serializable.

No I/O, no network, no LLM, no Mongo, no execution of any kind is represented
here.
"""

